              <li>
                <strong>自托管实例认证 Cookie：</strong
                >由相应部署管理员设置，用于维持本地实例登录。属性通常包括 HttpOnly、Secure（HTTPS
                下）与 SameSite=Lax，期限由实例配置决定。
              </li>
              <li>
                <strong>OIDC 流程 Cookie/服务端状态：</strong>用于保存短期 state、nonce、PKCE
                和错误提示，通常约 10 分钟，并在流程完成后消费或失效。
              </li>
              <li>
                <strong>本地偏好：</strong>浏览器 localStorage 可保存主题、外观及“不再提示绑定
                Passkey”等偏好；这些数据留在当前浏览器，直至用户清理或设置被覆盖。
              </li>
              <li>
                <strong>安全状态：</strong>sessionStorage
                可保存自动跳转防循环标识和一次性登录后状态，通常在标签页关闭时清除。
              </li>
              <li>
                <strong>Passkey 辅助标识：</strong>浏览器可保存 credential ID
                的摘要，用于判断是否提示已知 Passkey；认证私钥由操作系统或安全密钥管理，fn-knock
                不读取私钥。
              </li>
              <li>
                <strong>首页演示数据：</strong
                >官网首页控制台中的运行时间、流量和拦截数字由浏览器本地生成，仅用于界面演示，不代表真实设备遥测，不上传至官方服务，也不用于画像。
              </li>
              <li>
                <strong>分析与广告：</strong>当前官网及认证页面未集成广告 Cookie 或行为分析
                SDK。若未来新增非必要统计，将另行告知并在需要时征求同意。
              </li>
            </ul>
            <p>
              禁用必要 Cookie 会导致登录、OIDC、退出或安全保护无法正常工作。您可通过浏览器设置清除
              Cookie 和站点存储，但这通常会退出登录并重置偏好。
